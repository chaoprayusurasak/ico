grant usage on schema public to anon, authenticated;

create table if not exists public.visitor_logs (
  id bigint generated by default as identity primary key,
  device_type text not null default 'Desktop',
  user_agent text,
  visit_date date not null default current_date,
  created_at timestamptz not null default now(),
  legacy_evaluation_id bigint
);

alter table public.visitor_logs
  add column if not exists device_type text not null default 'Desktop',
  add column if not exists user_agent text,
  add column if not exists visit_date date not null default current_date,
  add column if not exists created_at timestamptz not null default now(),
  add column if not exists legacy_evaluation_id bigint;

create table if not exists public.visitor_stats (
  key text primary key,
  total_count bigint not null default 1,
  updated_at timestamptz not null default now()
);

alter table public.visitor_stats
  add column if not exists total_count bigint not null default 1,
  add column if not exists updated_at timestamptz not null default now();

create unique index if not exists visitor_logs_legacy_evaluation_id_key
  on public.visitor_logs (legacy_evaluation_id)
  where legacy_evaluation_id is not null;

create table if not exists public.faqs (
  id bigint generated by default as identity primary key,
  category text not null default 'eval_faq',
  code text,
  title text not null,
  type text not null default 'คำถาม',
  question_detail text not null,
  status text not null default 'รอการตอบ',
  admin_answer text,
  created_at timestamptz not null default now(),
  legacy_evaluation_id bigint
);

alter table public.faqs
  add column if not exists category text not null default 'eval_faq',
  add column if not exists code text,
  add column if not exists title text,
  add column if not exists type text not null default 'คำถาม',
  add column if not exists question_detail text,
  add column if not exists status text not null default 'รอการตอบ',
  add column if not exists admin_answer text,
  add column if not exists created_at timestamptz not null default now(),
  add column if not exists legacy_evaluation_id bigint;

create unique index if not exists faqs_legacy_evaluation_id_key
  on public.faqs (legacy_evaluation_id)
  where legacy_evaluation_id is not null;

do $$
begin
  if to_regclass('public.evaluations') is not null then
    execute 'alter table public.evaluations add column if not exists admin_answer text';
    execute 'alter table public.evaluations add column if not exists status text';
    execute 'drop policy if exists "Authenticated users can read FAQ evaluations" on public.evaluations';
    execute 'drop policy if exists "Authenticated users can reply to FAQ evaluations" on public.evaluations';
    execute 'drop policy if exists "Authenticated users can delete FAQ evaluations" on public.evaluations';

    insert into public.visitor_logs (
      device_type, user_agent, visit_date, created_at, legacy_evaluation_id
    )
    select
      coalesce(nullif(level_label, ''), 'Desktop'),
      improvement_suggestion,
      case
        when comments ~ '^\d{4}-\d{2}-\d{2}$' then comments::date
        else created_at::date
      end,
      created_at,
      id
    from public.evaluations
    where category = 'visitor_log'
      and not exists (
        select 1 from public.visitor_logs v
        where v.legacy_evaluation_id = evaluations.id
      );

    update public.faqs f
    set legacy_evaluation_id = e.id
    from public.evaluations e
    where e.category = 'eval_faq'
      and f.category = 'eval_faq'
      and f.legacy_evaluation_id is null
      and f.code = coalesce(nullif(trim(split_part(e.level_label, '|', 2)), ''), '611470/' || e.id::text);

    insert into public.faqs (
      category, code, title, type, question_detail, status, admin_answer, created_at, legacy_evaluation_id
    )
    select
      'eval_faq',
      coalesce(nullif(trim(split_part(level_label, '|', 2)), ''), '611470/' || id::text),
      coalesce(nullif(improvement_suggestion, ''), 'ไม่ระบุเรื่อง'),
      coalesce(nullif(trim(split_part(level_label, '|', 1)), ''), 'คำถาม'),
      coalesce(nullif(comments, ''), 'ไม่มีรายละเอียด'),
      coalesce(nullif(status, ''), 'รอการตอบ'),
      admin_answer,
      created_at,
      id
    from public.evaluations
    where category = 'eval_faq'
      and not exists (
        select 1 from public.faqs f
        where f.legacy_evaluation_id = evaluations.id
      );

    delete from public.evaluations e
    where e.category = 'visitor_log'
      and exists (
        select 1 from public.visitor_logs v
        where v.legacy_evaluation_id = e.id
      );

    delete from public.evaluations e
    where e.category = 'eval_faq'
      and exists (
        select 1 from public.faqs f
        where f.legacy_evaluation_id = e.id
      );
  end if;

  if to_regclass('public.items') is not null then
    insert into public.visitor_stats (key, total_count)
    select
      'site_total',
      case
        when max(case when description ~ '^\d+$' then description::bigint end) > 10000 then 1
        else greatest(1, coalesce(max(case when description ~ '^\d+$' then description::bigint end), 1))
      end
    from public.items
    where category = 'site_stats' and title = 'visitor_count'
    having count(*) > 0
    on conflict (key) do update
      set total_count = greatest(visitor_stats.total_count, excluded.total_count),
          updated_at = now();

    delete from public.items i
    where i.category = 'site_stats'
      and i.title = 'visitor_count'
      and exists (
        select 1 from public.visitor_stats v where v.key = 'site_total'
      );
  end if;
end;
$$;

alter table public.visitor_logs enable row level security;
alter table public.visitor_stats enable row level security;
alter table public.faqs enable row level security;

grant select, insert on public.visitor_logs to anon, authenticated;
grant select, insert, update on public.visitor_stats to anon, authenticated;
grant select, insert on public.faqs to anon, authenticated;
grant update, delete on public.faqs to authenticated;

do $$
declare
  visitor_sequence text := pg_get_serial_sequence('public.visitor_logs', 'id');
  faq_sequence text := pg_get_serial_sequence('public.faqs', 'id');
begin
  if visitor_sequence is not null then
    execute format('grant usage, select on sequence %s to anon, authenticated', visitor_sequence);
  end if;
  if faq_sequence is not null then
    execute format('grant usage, select on sequence %s to anon, authenticated', faq_sequence);
  end if;
end;
$$;

drop policy if exists "Public can read visitor logs" on public.visitor_logs;
create policy "Public can read visitor logs"
  on public.visitor_logs for select
  to anon, authenticated
  using (true);

drop policy if exists "Public can add visitor logs" on public.visitor_logs;
create policy "Public can add visitor logs"
  on public.visitor_logs for insert
  to anon, authenticated
  with check (true);

drop policy if exists "Public can read visitor stats" on public.visitor_stats;
create policy "Public can read visitor stats"
  on public.visitor_stats for select
  to anon, authenticated
  using (true);

drop policy if exists "Public can initialize visitor stats" on public.visitor_stats;
create policy "Public can initialize visitor stats"
  on public.visitor_stats for insert
  to anon, authenticated
  with check (key = 'site_total' and total_count >= 1);

drop policy if exists "Public can update visitor stats" on public.visitor_stats;
create policy "Public can update visitor stats"
  on public.visitor_stats for update
  to anon, authenticated
  using (key = 'site_total')
  with check (key = 'site_total' and total_count >= 1);

drop policy if exists "Public can read FAQs" on public.faqs;
create policy "Public can read FAQs"
  on public.faqs for select
  to anon, authenticated
  using (true);

drop policy if exists "Public can submit FAQs" on public.faqs;
create policy "Public can submit FAQs"
  on public.faqs for insert
  to anon, authenticated
  with check (category = 'eval_faq');

drop policy if exists "Authenticated users can reply to FAQs" on public.faqs;
create policy "Authenticated users can reply to FAQs"
  on public.faqs for update
  to authenticated
  using (auth.uid() is not null and category = 'eval_faq')
  with check (auth.uid() is not null and category = 'eval_faq');

drop policy if exists "Authenticated users can delete FAQs" on public.faqs;
create policy "Authenticated users can delete FAQs"
  on public.faqs for delete
  to authenticated
  using (auth.uid() is not null and category = 'eval_faq');

notify pgrst, 'reload schema';
